export const getEventsByCategory = (categoryId) => {
  return activitiesData.filter(event => event.categoryId === categoryId);
};

export const getEventsBySubCategory = (categoryId, subCategoryId) => {
  const safeSubId = subCategoryId ? subCategoryId.toLowerCase().replace(/%20| /g, '-') : '';
  return activitiesData.filter(event => event.categoryId === categoryId && (event.subCategoryId === safeSubId || safeSubId === 'all'));
};

export const getEventById = (id) => {
  if (!id) return null;
  const cleanId = decodeURIComponent(id).toLowerCase().trim();
  return activitiesData.find(event => 
    event.id.toLowerCase() === cleanId || 
    event.id.toLowerCase().replace(/[^a-z0-9]/g, '') === cleanId.replace(/[^a-z0-9]/g, '')
  );
};
